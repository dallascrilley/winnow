#!/usr/bin/env node
/**
 * Regenerate server/db/migrations-sql.ts from the drizzle-kit output in
 * server/db/migrations (sqlite) and server/db/migrations-pg (postgres).
 *
 * Why this exists: the action CLI's db-plugin convention loads
 * server/plugins/db.ts under tsx, which cannot parse .sql?raw imports —
 * the plugin needs the SQL as string constants instead.
 *
 * Usage (from the app dir):
 *   DATABASE_URL= pnpm exec drizzle-kit generate                       # sqlite diff
 *   DATABASE_URL=postgres://… pnpm exec drizzle-kit generate --config=drizzle.pg.config.ts
 *   node scripts/wrap-migrations.mjs
 */
import fs from "node:fs";
import path from "node:path";

const SQLITE_DIR = "server/db/migrations";
const PG_DIR = "server/db/migrations-pg";
const OUT = "server/db/migrations-sql.ts";

function journalEntries(dir) {
  const journal = JSON.parse(
    fs.readFileSync(path.join(dir, "meta", "_journal.json"), "utf8"),
  );
  return journal.entries.map((entry) => ({
    idx: entry.idx,
    tag: entry.tag,
    file: path.join(dir, `${entry.tag}.sql`),
  }));
}

const sqliteEntries = journalEntries(SQLITE_DIR);
const pgEntries = journalEntries(PG_DIR);

if (sqliteEntries.length !== pgEntries.length) {
  console.error(
    `journal mismatch: ${sqliteEntries.length} sqlite vs ${pgEntries.length} pg migrations — regenerate the missing dialect first`,
  );
  process.exit(1);
}

const entries = sqliteEntries.map((entry, i) => ({
  version: entry.idx + 1,
  // Strip drizzle's NNNN_ prefix so names stay stable across regenerations —
  // the runner records applied migrations by name, and v1 was first applied
  // as "init-scheduling".
  name: entry.tag.replace(/^\d+_/, ""),
  sqlite: fs.readFileSync(entry.file, "utf8"),
  postgres: fs.readFileSync(pgEntries[i].file, "utf8"),
}));

const body = `// GENERATED by scripts/wrap-migrations.mjs — do not edit by hand.
// Regenerate after any drizzle-kit generate run (see script header).
export const migrationsSql = ${JSON.stringify(entries, null, 2)};
`;

fs.writeFileSync(OUT, body);
console.log(`wrote ${OUT} with ${entries.length} migration(s)`);
